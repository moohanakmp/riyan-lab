-- Schema selection is handled by Flyway's default-schema=riyan_lab.
CREATE TABLE IF NOT EXISTS auto_signals (
    id BIGSERIAL PRIMARY KEY,
    source_id TEXT NOT NULL UNIQUE,
    symbol TEXT,
    direction TEXT,
    status TEXT,
    event_time TIMESTAMPTZ,
    payload JSONB NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS manual_signals (LIKE auto_signals INCLUDING CONSTRAINTS INCLUDING INDEXES INCLUDING DEFAULTS);
CREATE TABLE IF NOT EXISTS low_profit_signals (LIKE auto_signals INCLUDING CONSTRAINTS INCLUDING INDEXES INCLUDING DEFAULTS);
CREATE TABLE IF NOT EXISTS analysis_reports (LIKE auto_signals INCLUDING CONSTRAINTS INCLUDING INDEXES INCLUDING DEFAULTS);
CREATE TABLE IF NOT EXISTS seven_day_predictions (LIKE auto_signals INCLUDING CONSTRAINTS INCLUDING INDEXES INCLUDING DEFAULTS);
CREATE TABLE IF NOT EXISTS pnl_reports (LIKE auto_signals INCLUDING CONSTRAINTS INCLUDING INDEXES INCLUDING DEFAULTS);
CREATE TABLE IF NOT EXISTS gold_predictions_actuals (LIKE auto_signals INCLUDING CONSTRAINTS INCLUDING INDEXES INCLUDING DEFAULTS);
CREATE TABLE IF NOT EXISTS research_reports (LIKE auto_signals INCLUDING CONSTRAINTS INCLUDING INDEXES INCLUDING DEFAULTS);
CREATE TABLE IF NOT EXISTS tab_states (LIKE auto_signals INCLUDING CONSTRAINTS INCLUDING INDEXES INCLUDING DEFAULTS);
CREATE TABLE IF NOT EXISTS audit_events (
    id BIGSERIAL PRIMARY KEY,
    record_type TEXT NOT NULL,
    source_id TEXT NOT NULL,
    action TEXT NOT NULL,
    actor TEXT,
    event_time TIMESTAMPTZ NOT NULL DEFAULT now(),
    old_payload JSONB,
    new_payload JSONB NOT NULL
);
CREATE INDEX IF NOT EXISTS audit_events_lookup_idx
    ON audit_events(record_type, source_id, event_time DESC);
